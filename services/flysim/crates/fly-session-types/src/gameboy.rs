/// The whole extension set: payload schemas with their references, and the declaration rows.
pub fn extension_set() -> Value {
    let mut payloads: Vec<&PayloadSchema> = PAYLOAD_SCHEMAS.iter().collect();
    payloads.sort_by_key(|p| p.id);
    let mut declarations: Vec<&TypeSchema> = DECLARATIONS.iter().collect();
    declarations.sort_by_key(|d| d.name);
    obj(vec![
        ("contract", "fly-session-types/legacy-gameboy".into()),
        ("version", Value::from(1u64)),
        (
            "scalars",
            obj(vec![(
                "ChannelName",
                "^[a-z][a-z0-9_]{0,63}$: a decoder channel or rate-role name; not an Id, because the legacy role names carry '_'".into(),
            )]),
        ),
        (
            "enums",
            obj(vec![
                (
                    "MacroMode",
                    Value::Array(MACRO_MODES.iter().map(|m| (*m).into()).collect()),
                ),
                (
                    "RollbackTrigger",
                    Value::Array(ROLLBACK_TRIGGERS.iter().map(|m| (*m).into()).collect()),
                ),
            ]),
        ),
        (
            "payloadSchemas",
            Value::Array(
                payloads
                    .iter()
                    .map(|p| {
                        obj(vec![
                            ("declaration", p.declaration()),
                            ("schemaRef", p.schema_ref().to_json()),
                        ])
                    })
                    .collect(),
            ),
        ),
        (
            "declarations",
            Value::Array(
                declarations
                    .iter()
                    .map(|d| {
                        obj(vec![
                            ("name", d.name.into()),
                            ("source", d.source.into()),
                            ("fields", fields_json(d.fields)),
                        ])
                    })
                    .collect(),
            ),
        ),
    ])
}

/// SHA-256 of the canonical extension set.
pub fn extension_set_digest() -> String {
    canonical::digest_of(&extension_set()).expect("canonicalizable")
}

