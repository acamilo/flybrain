/// `gameboy-channels-v1`: the eight joypad channels and the macro group's active channel.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ChannelsDecision {
    /// In [`GAMEBOY_BUTTONS`] order.
    pub buttons: [bool; 8],
    pub macro_channel: Option<String>,
}

impl ChannelsDecision {
    pub fn from_typed(value: &TypedValue) -> Result<ChannelsDecision> {
        typed(value, &CHANNELS)
    }

    pub fn to_typed(&self) -> TypedValue {
        wrap(self, &CHANNELS)
    }

    /// The joypad mask, bit `i` for `GAMEBOY_BUTTONS[i]`.
    pub fn mask(&self) -> u8 {
        self.buttons.iter().enumerate().fold(
            0u8,
            |mask, (bit, down)| if *down { mask | (1 << bit) } else { mask },
        )
    }

    /// The macro group only ever activates a bound channel (`docs/readout.md`, "Macro group").
    pub fn validate_against(&self, context: &ReadoutContext) -> Result<()> {
        self.validate()?;
        if let Some(channel) = &self.macro_channel
            && !context.bound.contains(channel)
        {
            return err(format!(
                "GameboyChannelsDecision: macro {channel:?} is not bound in the decision context"
            ));
        }
        Ok(())
    }
}

impl DomainType for ChannelsDecision {
    const TYPE_NAME: &'static str = "GameboyChannelsDecision";

    fn from_json(value: &Value) -> Result<ChannelsDecision> {
        let mut f = Fields::new(value, "GameboyChannelsDecision")?;
        let items = f.array("buttons", 8, 8)?;
        let mut buttons = [false; 8];
        for (index, item) in items.iter().enumerate() {
            let mut b = Fields::new(item, "GameboyChannelsDecision.buttons")?;
            let id = b.id("id")?;
            let down = b.boolean("down")?;
            b.finish()?;
            if id != GAMEBOY_BUTTONS[index] {
                return err(format!(
                    "GameboyChannelsDecision: buttons must list {} in that order",
                    GAMEBOY_BUTTONS.join(",")
                ));
            }
            buttons[index] = down;
        }
        let macro_channel = match f.value("macro")? {
            Value::Null => None,
            Value::String(s) if is_channel_name(s) => Some(s.clone()),
            _ => return err("GameboyChannelsDecision: macro must be null or a channel name"),
        };
        f.finish()?;
        let d = ChannelsDecision {
            buttons,
            macro_channel,
        };
        d.validate()?;
        Ok(d)
    }

    fn to_json(&self) -> Value {
        obj(vec![
            (
                "buttons",
                Value::Array(
                    GAMEBOY_BUTTONS
                        .iter()
                        .zip(self.buttons)
                        .map(|(id, down)| obj(vec![("id", (*id).into()), ("down", down.into())]))
                        .collect(),
                ),
            ),
            (
                "macro",
                self.macro_channel
                    .clone()
                    .map_or(Value::Null, Value::String),
            ),
        ])
    }

    fn validate(&self) -> Result<()> {
        if let Some(channel) = &self.macro_channel
            && !is_channel_name(channel)
        {
            return err("GameboyChannelsDecision: macro must be a channel name");
        }
        Ok(())
    }
}

