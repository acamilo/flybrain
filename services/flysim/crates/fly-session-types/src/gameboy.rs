/// `ChannelName`: a decoder channel or rate-role name, `^[a-z][a-z0-9_]{0,63}$`.
pub fn is_channel_name(s: &str) -> bool {
    let bytes = s.as_bytes();
    !bytes.is_empty()
        && bytes.len() <= 64
        && bytes[0].is_ascii_lowercase()
        && bytes
            .iter()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || *b == b'_')
}

fn channel_list(f: &mut Fields<'_>, key: &'static str, hi: usize) -> Result<Vec<String>> {
    let items = f.array(key, 0, hi)?;
    let mut out = Vec::with_capacity(items.len());
    for item in items {
        match item.as_str() {
            Some(s) if is_channel_name(s) => out.push(s.to_owned()),
            _ => return err(format!("{key}: every entry must be a channel name")),
        }
    }
    require_unique(out.iter().map(String::as_str), key)?;
    Ok(out)
}

fn u32_int(f: &mut Fields<'_>, key: &'static str) -> Result<u32> {
    Ok(f.int(key, 0, u64::from(u32::MAX))? as u32)
}

fn exact(found: &str, expected: &str, what: &str) -> Result<()> {
    if found != expected {
        return err(format!("{what} must be {expected:?}, found {found:?}"));
    }
    Ok(())
}

fn id_array(f: &mut Fields<'_>, key: &'static str, lo: usize, hi: usize) -> Result<Vec<String>> {
    let ids = crate::scalar::id_list(f, key, lo, hi)?;
    require_unique(ids.iter().map(String::as_str), key)?;
    Ok(ids)
}

fn schema_matches(found: &SchemaRef, schema: &PayloadSchema, what: &str) -> Result<()> {
    if *found != schema.schema_ref() {
        return err(format!(
            "{what} must be the registered {} reference",
            schema.id
        ));
    }
    Ok(())
}

/// Reads a `TypedValue` of a registered schema, refusing any other reference.
fn typed<T: DomainType>(value: &TypedValue, schema: &PayloadSchema) -> Result<T> {
    schema_matches(&value.schema, schema, "TypedValue.schema")?;
    T::from_json(&value.value)
}

fn wrap<T: DomainType>(value: &T, schema: &PayloadSchema) -> TypedValue {
    TypedValue::new(schema.schema_ref(), value.to_json()).expect("a registered value fits")
}

