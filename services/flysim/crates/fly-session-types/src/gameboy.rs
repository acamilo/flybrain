// The legacy profile

/// The legacy profile document. There is exactly one: every field is fixed, so the document
/// and its digest are constants of this contract, and a different value is a different
/// profile that needs its own id.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LegacyProfile {
    pub dataset_fingerprint: String,
    pub readout_context_schema: SchemaRef,
    pub decision_schema: SchemaRef,
}

/// The one legacy profile.
pub fn legacy_profile() -> LegacyProfile {
    LegacyProfile {
        dataset_fingerprint: FAFB_V783_FINGERPRINT.to_owned(),
        readout_context_schema: READOUT_CONTEXT.schema_ref(),
        decision_schema: CHANNELS.schema_ref(),
    }
}

/// SHA-256 of the legacy profile's canonical JSON: its `AssetRef.digest`.
pub fn profile_digest() -> String {
    canonical::digest_of(&legacy_profile().to_json()).expect("canonicalizable")
}

/// The canonical byte length of the profile document: its `AssetRef.byteLength`.
pub fn profile_byte_length() -> u64 {
    canonical::canonicalize(&legacy_profile().to_json())
        .expect("canonicalizable")
        .len() as u64
}

/// The `AssetRef` naming the profile document.
pub fn profile_asset_ref() -> AssetRef {
    AssetRef {
        id: PROFILE_ID.to_owned(),
        digest: profile_digest(),
        byte_length: profile_byte_length(),
        format: PROFILE_FORMAT.to_owned(),
    }
}

impl DomainType for LegacyProfile {
    const TYPE_NAME: &'static str = "LegacyGameboyProfile";

    fn from_json(value: &Value) -> Result<LegacyProfile> {
        let mut f = Fields::new(value, "LegacyGameboyProfile")?;
        exact(f.string("profileId")?, PROFILE_ID, "profileId")?;
        exact(f.string("datasetId")?, DATASET_ID, "datasetId")?;
        f.int("fingerprintSchema", FINGERPRINT_SCHEMA, FINGERPRINT_SCHEMA)?;
        let dataset_fingerprint = f.string("datasetFingerprint")?.to_owned();
        exact(f.string("kernelVersion")?, KERNEL_VERSION, "kernelVersion")?;
        exact(
            f.string("plasticityVersion")?,
            PLASTICITY_VERSION,
            "plasticityVersion",
        )?;
        let tick = RationalNs::from_json(f.value("tickDuration")?)?;
        if tick != tick_duration() {
            return err("LegacyGameboyProfile: tickDuration must be 1 ms (1000000/1)");
        }
        f.int("warmupMs", WARMUP_MS, WARMUP_MS)?;
        {
            let mut v = Fields::new(f.value("view")?, "LegacyGameboyProfile.view")?;
            exact(&v.id("viewId")?, VIEW_ID, "view.viewId")?;
            v.int("width", VIEW_WIDTH, VIEW_WIDTH)?;
            v.int("height", VIEW_HEIGHT, VIEW_HEIGHT)?;
            v.finish()?;
        }
        let stimuli = id_array(&mut f, "supportedStimuli", 1, 1)?;
        exact(&stimuli[0], STIMULUS_REWARD_PULSE, "supportedStimuli[0]")?;
        let readout_context_schema = SchemaRef::from_json(f.value("readoutContextSchema")?)?;
        let decision_schema = SchemaRef::from_json(f.value("decisionSchema")?)?;
        let exceptions = id_array(&mut f, "legacyExceptions", 1, 1)?;
        exact(&exceptions[0], EXCEPTION_MACRO_ROLES, "legacyExceptions[0]")?;
        f.finish()?;
        let p = LegacyProfile {
            dataset_fingerprint,
            readout_context_schema,
            decision_schema,
        };
        p.validate()?;
        Ok(p)
    }

    fn to_json(&self) -> Value {
        obj(vec![
            ("profileId", PROFILE_ID.into()),
            ("datasetId", DATASET_ID.into()),
            ("fingerprintSchema", Value::from(FINGERPRINT_SCHEMA)),
            (
                "datasetFingerprint",
                self.dataset_fingerprint.clone().into(),
            ),
            ("kernelVersion", KERNEL_VERSION.into()),
            ("plasticityVersion", PLASTICITY_VERSION.into()),
            ("tickDuration", tick_duration().to_json()),
            ("warmupMs", Value::from(WARMUP_MS)),
            (
                "view",
                obj(vec![
                    ("viewId", VIEW_ID.into()),
                    ("width", Value::from(VIEW_WIDTH)),
                    ("height", Value::from(VIEW_HEIGHT)),
                ]),
            ),
            (
                "supportedStimuli",
                Value::Array(vec![STIMULUS_REWARD_PULSE.into()]),
            ),
            (
                "readoutContextSchema",
                self.readout_context_schema.to_json(),
            ),
            ("decisionSchema", self.decision_schema.to_json()),
            (
                "legacyExceptions",
                Value::Array(vec![EXCEPTION_MACRO_ROLES.into()]),
            ),
        ])
    }

    fn validate(&self) -> Result<()> {
        if self.dataset_fingerprint != FAFB_V783_FINGERPRINT {
            return err(
                "LegacyGameboyProfile: datasetFingerprint must be today's fafb-v783 schema-1 fingerprint; another fingerprint is another profile",
            );
        }
        schema_matches(
            &self.readout_context_schema,
            &READOUT_CONTEXT,
            "LegacyGameboyProfile.readoutContextSchema",
        )?;
        schema_matches(
            &self.decision_schema,
            &CHANNELS,
            "LegacyGameboyProfile.decisionSchema",
        )
    }
}

