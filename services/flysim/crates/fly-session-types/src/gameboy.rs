/// A registered `TypedValue` payload schema.
#[derive(Clone, Copy, Debug)]
pub struct PayloadSchema {
    pub id: &'static str,
    pub version: u16,
    /// Where the schema is specified.
    pub source: &'static str,
    pub fields: &'static [FieldSchema],
}

impl PayloadSchema {
    /// The declaration the digest is taken over.
    pub fn declaration(&self) -> Value {
        obj(vec![
            ("registry", "fly-session-payload-schema-v1".into()),
            ("id", self.id.into()),
            ("version", Value::from(u64::from(self.version))),
            ("source", self.source.into()),
            ("fields", fields_json(self.fields)),
        ])
    }

    /// `SchemaRef` whose digest is the SHA-256 of the canonical declaration.
    pub fn schema_ref(&self) -> SchemaRef {
        let digest = canonical::digest_of(&self.declaration()).expect("canonicalizable");
        SchemaRef::new(self.id, self.version, &digest).expect("a registered schema is valid")
    }
}

fn fields_json(fields: &[FieldSchema]) -> Value {
    Value::Array(
        fields
            .iter()
            .map(|f| {
                obj(vec![
                    ("name", f.name.into()),
                    ("kind", f.kind.into()),
                    ("required", Value::Bool(f.required)),
                    ("constraint", f.constraint.into()),
                ])
            })
            .collect(),
    )
}

