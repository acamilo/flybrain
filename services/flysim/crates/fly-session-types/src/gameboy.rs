/// Where the player is: the adapter's `(area, x, y)`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Location {
    pub area: u32,
    pub x: u32,
    pub y: u32,
}

/// `gameboy-readout-context-v1`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ReadoutContext {
    pub boot: bool,
    pub bound: Vec<String>,
    pub location: Option<Location>,
}

impl ReadoutContext {
    pub fn from_typed(value: &TypedValue) -> Result<ReadoutContext> {
        typed(value, &READOUT_CONTEXT)
    }

    pub fn to_typed(&self) -> TypedValue {
        wrap(self, &READOUT_CONTEXT)
    }

    /// `bound` is a subset of the composition's macro channels, in their order.
    pub fn validate_against(&self, macro_channels: &[String]) -> Result<()> {
        self.validate()?;
        let mut cursor = 0;
        for channel in &self.bound {
            match macro_channels[cursor..].iter().position(|c| c == channel) {
                Some(offset) => cursor += offset + 1,
                None => {
                    return err(format!(
                        "ReadoutContext: bound channel {channel:?} is not a macro channel of the composition, or is out of order"
                    ));
                }
            }
        }
        Ok(())
    }
}

impl DomainType for ReadoutContext {
    const TYPE_NAME: &'static str = "GameboyReadoutContext";

    fn from_json(value: &Value) -> Result<ReadoutContext> {
        let mut f = Fields::new(value, "GameboyReadoutContext")?;
        let boot = f.boolean("boot")?;
        let bound = channel_list(&mut f, "bound", MAX_MACRO_CHANNELS)?;
        let location = match f.value("location")? {
            Value::Null => None,
            v => {
                let mut l = Fields::new(v, "GameboyReadoutContext.location")?;
                let area = u32_int(&mut l, "area")?;
                let x = u32_int(&mut l, "x")?;
                let y = u32_int(&mut l, "y")?;
                l.finish()?;
                Some(Location { area, x, y })
            }
        };
        f.finish()?;
        let c = ReadoutContext {
            boot,
            bound,
            location,
        };
        c.validate()?;
        Ok(c)
    }

    fn to_json(&self) -> Value {
        obj(vec![
            ("boot", Value::Bool(self.boot)),
            (
                "bound",
                Value::Array(self.bound.iter().map(|b| b.clone().into()).collect()),
            ),
            (
                "location",
                self.location.map_or(Value::Null, |l| {
                    obj(vec![
                        ("area", Value::from(l.area)),
                        ("x", Value::from(l.x)),
                        ("y", Value::from(l.y)),
                    ])
                }),
            ),
        ])
    }

    fn validate(&self) -> Result<()> {
        if self.bound.len() > MAX_MACRO_CHANNELS {
            return err("GameboyReadoutContext: at most 64 bound channels");
        }
        if let Some(bad) = self.bound.iter().find(|b| !is_channel_name(b)) {
            return err(format!(
                "GameboyReadoutContext: {bad:?} is not a channel name"
            ));
        }
        require_unique(
            self.bound.iter().map(String::as_str),
            "GameboyReadoutContext.bound",
        )
    }
}

