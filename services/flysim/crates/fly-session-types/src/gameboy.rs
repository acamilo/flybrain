//! The legacy Game Boy composition's registered schemas and declarations (PROF-02a).
//!
//! [`legacy-gameboy-v1`] is the contract. The operator decided on 2026-09-23 that the live fly
//! is ported onto the session framework as a declared legacy profile rather than kept outside
//! it; this module is the machine-readable half of that decision.
//!
//! Nothing here is a generic session type. Every value below travels inside a `TypedValue`
//! (whose [`SchemaRef`] names one of [`PAYLOAD_SCHEMAS`]) or is a document an `AssetRef` or the
//! composition digest names. The generic types in [`crate::workers`] stay free of console
//! state, which is what `workers-v1` section 6 and ENV-01's acceptance require.
//!
//! - A **payload schema** is a declaration `(id, version, source, fields)`. Its `SchemaRef`
//!   digest is the SHA-256 of that declaration's canonical JSON, so the reference changes when
//!   a field, kind or constraint does and not when this file is reformatted -- the rule
//!   `contractDigest` follows for the session schema set.
//! - The **legacy profile** `gameboy-legacy-fafb-v783-v1` is one fixed document. Its
//!   `AssetRef.digest` is the SHA-256 of its canonical JSON ([`profile_digest`]).
//! - The **legacy composition** declaration carries everything that is behaviour but is not
//!   in the legacy compatibility string -- the decoder configuration and the macro channels
//!   among them -- and its digest joins the session's `compositionDigest`.
//!
//! `fixtures/gameboy-legacy.json` is the rendered set with every digest, regenerated by the
//! `update_fixtures` example and read by `packages/session-types`.
//!
//! [`legacy-gameboy-v1`]: ../../../../docs/design/session-framework/legacy-gameboy-v1.md

